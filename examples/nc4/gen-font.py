#!/usr/bin/env python3
# Render printable ASCII of a monospace TTF into an 8-bit alpha atlas header:
#
#   python3 gen-font.py /usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf 20 > font.h
#
# font.h in this directory is generated from DejaVu Sans Mono (Bitstream Vera
# license, which allows redistributing modified versions of the font data).
import sys

from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 32, 126

path, size = sys.argv[1], int(sys.argv[2])
font = ImageFont.truetype(path, size)
ascent, descent = font.getmetrics()
cell_w = max(int(round(font.getlength(chr(c)))) for c in range(FIRST, LAST + 1))
cell_h = ascent + descent
count = LAST - FIRST + 1

atlas = Image.new("L", (cell_w * count, cell_h), 0)
draw = ImageDraw.Draw(atlas)
for i, c in enumerate(range(FIRST, LAST + 1)):
    draw.text((i * cell_w, 0), chr(c), font=font, fill=255)

data = atlas.tobytes()
print("/* generated by gen-font.py from %s, %dpx */" % (path.rsplit("/", 1)[-1], size))
print("#pragma once")
print()
print("#define FONT_FIRST %d" % FIRST)
print("#define FONT_COUNT %d" % count)
print("#define FONT_CELL_W %d" % cell_w)
print("#define FONT_CELL_H %d" % cell_h)
print("/* %d x %d, one 8-bit alpha value per pixel */" % (cell_w * count, cell_h))
print("static const unsigned char font_atlas[] =")
for off in range(0, len(data), 40):
    print('    "%s"' % "".join("\\x%02x" % b for b in data[off:off + 40]))
print(";")
